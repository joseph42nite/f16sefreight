/**
 * Which Bootstrap icons this app uses — and nothing more (2026-11-15 frontend audit, FP3).
 *
 * The app registered the whole set, 1,371 icons, for every visitor. This writes the list of the ones the source
 * actually names to resources/js/src/core/plugins/bootstrap-icons.generated.js, which is what gets registered.
 *
 * 🔴 HOW A NAME IS FOUND: every quoted word in resources/js/src that is the name of a Bootstrap icon is kept,
 * wherever it appears. That is deliberately generous. An icon is not always written as icon="truck": seventeen
 * places choose one at run time (`:icon="item.icon"`, with `icon: "truck"` far away in a list). Keeping any quoted
 * word that IS an icon name catches all of those without having to follow the code; the cost is a few icons that
 * are only words. The one thing it cannot see is a name built from pieces ("arrow-" + side): do not do that.
 *
 * Run by the build (webpack.mix.js) before every compile, so a new icon in a page is picked up without anyone
 * remembering this file. `node build/used-icons.js --check` exits 1 when the written list is out of date.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SOURCE = path.join(ROOT, "resources/js/src");
const TARGET = path.join(SOURCE, "core/plugins/bootstrap-icons.generated.js");

const pascal = (name) => name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");

function files(dir, found = []) {
  fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
    const file = path.join(dir, entry.name);

    // The old theme's own scripts name no icons of this set, and the list must not read itself.
    if (entry.isDirectory()) return entry.name === "assets" ? null : files(file, found);
    if (/\.(vue|js)$/.test(entry.name) && file !== TARGET) found.push(file);

    return null;
  });

  return found;
}

function usedIcons() {
  const library = require("bootstrap-vue");
  const exists = (component) => Object.prototype.hasOwnProperty.call(library, component);
  const used = new Set();

  files(SOURCE).forEach((file) => {
    const words = fs.readFileSync(file, "utf8").match(/["'`][a-z0-9]+(?:-[a-z0-9]+)*["'`]/g) || [];

    words.forEach((quoted) => {
      const component = "BIcon" + pascal(quoted.slice(1, -1));

      if (component !== "BIcon" && component !== "BIconstack" && exists(component)) used.add(component);
    });
  });

  return [...used].sort();
}

function render(icons) {
  return [
    "// GENERATED by build/used-icons.js — do not edit. The Bootstrap icons the source names, and no others.",
    "// The build rewrites it before every compile; `node build/used-icons.js` does it by hand.",
    "import {",
    "  BIcon,",
    "  BIconstack,",
    ...icons.map((icon) => `  ${icon},`),
    '} from "bootstrap-vue";',
    "",
    "export default {",
    "  BIcon,",
    "  BIconstack,",
    ...icons.map((icon) => `  ${icon},`),
    "};",
    "",
  ].join("\n");
}

function write() {
  const wanted = render(usedIcons());
  const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";

  // Left alone when nothing changed, so a build does not touch a tracked file for no reason.
  if (wanted !== have) fs.writeFileSync(TARGET, wanted);

  return wanted !== have;
}

module.exports = { usedIcons, render, write, TARGET };

if (require.main === module) {
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(TARGET) && fs.readFileSync(TARGET, "utf8") === render(usedIcons());

    if (!current) console.error("The icon list is out of date. Run: node build/used-icons.js");
    process.exit(current ? 0 : 1);
  }

  console.log(write() ? "Icon list rewritten:" : "Icon list already current:", usedIcons().length, "icons");
}
